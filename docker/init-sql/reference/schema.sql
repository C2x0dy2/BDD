CREATE VIEW public.category_sales_view AS
 SELECT c.id AS category_id,
    c.name AS category_name,
    count(DISTINCT p.id) AS product_count,
    COALESCE(sum(oi.quantity), (0)::bigint) AS units_sold,
    COALESCE(sum(((oi.quantity)::numeric * oi.price)), (0)::numeric) AS revenue
   FROM (((public.e_commerce_category c
     LEFT JOIN public.e_commerce_product p ON ((p.category_id = c.id)))
     LEFT JOIN public.e_commerce_orderitem oi ON ((oi.product_id = p.id)))
     LEFT JOIN public.e_commerce_order o ON (((o.id = oi.order_id) AND ((o.payment_status)::text = 'paid'::text))))
  GROUP BY c.id, c.name;


